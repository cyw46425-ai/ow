async function requestJson(url, attempts = 4) {
  for (let attempt = 1; attempt <= attempts; attempt += 1) {
    const response = await fetch(url, { headers: { "user-agent": "ow-rookie-assistant-content-sync/1.0" } });
    if (response.ok) return response.json();
    if (attempt === attempts) throw new Error(`${response.status} ${response.statusText}: ${url}`);
    await new Promise((resolve) => setTimeout(resolve, attempt * 1200));
  }
}

const list = await requestJson(`${API}/heroes?locale=${locale}`);
const details = [];
for (let index = 0; index < list.length; index += 4) {
  const batch = list.slice(index, index + 4);
  const records = await Promise.all(batch.map((hero) => requestJson(`${API}/heroes/${hero.key}?locale=${locale}`)));
  records.forEach((record, offset) => details.push({ key: batch[offset].key, ...record }));
  await new Promise((resolve) => setTimeout(resolve, 350));
}

const catalogue = details.map((hero) => ({
  id: hero.key.replaceAll("-", ""),
  key: hero.key,
  name: names[hero.key] || hero.name,
  localizedName: hero.name,
  aliases: aliases[hero.key] || [],
  role: roleNames[hero.role] || hero.role,
  health: hero.hitpoints?.total ?? null,
  armor: hero.hitpoints?.armor ?? 0,
  shields: hero.hitpoints?.shields ?? 0,
  abilities: (hero.abilities || []).map((ability) => ({ name: ability.name, description: ability.description })),
  source: `https://overwatch.blizzard.com/zh-tw/heroes/${hero.key}/`,
  verifiedAt: reviewedAt
}));

